async def test_chat_follow_up_updates_one_row(client):
    async with _no_llm():
        r1 = await client.post("/api/v1/therapy/chat",
                               json={"message": "I feel anxious about tomorrow", "emotion_override": "anxiety"})
        assert r1.status_code == 200, r1.text
        first = r1.json()
        try:
            r2 = await client.post("/api/v1/therapy/chat", json={
                "message": "I am still sad about what happened",
                "emotion_override": "sadness",
                "session_id": first["session_id"],
                "session_token": first["client_token"],
            })
            assert r2.status_code == 200, r2.text
            assert "duplicate key" not in r2.text and "UniqueViolation" not in r2.text
            second = r2.json()
            assert second["session_id"] == first["session_id"]
            assert second["client_token"] is None
            rows = await _sql("SELECT emotion FROM therapy_sessions WHERE session_id = :s", s=first["session_id"])
            assert [r[0] for r in rows] == ["sadness"]
        finally:
            await _drop(first["session_id"])


async def test_chat_cannot_attach_to_someone_elses_session(client):
    victim = await _ask(client)
    async with _no_llm():
        r = await client.post("/api/v1/therapy/chat", json={
            "message": "I feel anxious about tomorrow",
            "session_id": victim["session_id"],
            "session_token": "guessed-token-123",
        })
    assert r.status_code == 200, r.text
    attacker = r.json()
    try:
        assert attacker["session_id"] != victim["session_id"]
        assert attacker["client_token"]
        rows = await _sql("SELECT emotion FROM therapy_sessions WHERE session_id = :s", s=victim["session_id"])
        assert len(rows) == 1
    finally:
        await _drop(victim["session_id"], attacker["session_id"])



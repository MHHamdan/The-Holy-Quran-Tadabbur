async def test_message_is_not_stored(client):
    sid = (await _ask(client))["session_id"]
    rows = await _sql("SELECT user_message, emotion FROM therapy_sessions WHERE session_id = :s", s=sid)
    assert rows and rows[0][0] is None and rows[0][1]
    await _drop(sid)


async def test_only_the_token_hash_is_stored(client):
    d = await _ask(client)
    assert d["client_token"] and len(d["client_token"]) >= 24
    rows = await _sql("SELECT client_token_hash FROM therapy_sessions WHERE session_id = :s", s=d["session_id"])
    assert rows[0][0] == hashlib.sha256(d["client_token"].encode()).hexdigest()
    assert d["client_token"] not in rows[0][0]
    await _drop(d["session_id"])


# ---------------------------------------------------------------- ownership (IDOR)

async def test_reflection_needs_the_token_to_read_write_or_delete(client):
    victim = await _ask(client)
    sid, token = victim["session_id"], victim["client_token"]
    try:
        r = await client.post("/api/v1/therapy/reflect",
                              json={"session_id": sid, "token": token, "reflection": "my private note"})
        assert r.status_code == 200, r.text

        # Attacker who learned the id but not the token
        r = await client.post("/api/v1/therapy/reflect", json={"session_id": sid, "reflection": "overwrite"})
        assert r.status_code == 422  # token is required
        r = await client.post("/api/v1/therapy/reflect",
                              json={"session_id": sid, "token": "wrong-token-123", "reflection": "overwrite"})
        assert r.status_code == 404  # same answer as an unknown id
        r = await client.post("/api/v1/therapy/reflections", json={"session_ids": [sid]})
        assert r.status_code == 422
        r = await client.post("/api/v1/therapy/reflections",
                              json={"sessions": [{"id": sid, "token": "wrong-token-123"}]})
        assert r.status_code == 200 and r.json()["reflections"] == []
        r = await client.post("/api/v1/therapy/insights",
                              json={"sessions": [{"id": sid, "token": "wrong-token-123"}]})
        assert r.status_code == 200 and r.json()["total_sessions"] == 0
        assert "my private note" not in r.text
        r = await client.post("/api/v1/therapy/sessions/delete",
                              json={"sessions": [{"id": sid, "token": "wrong-token-123"}]})
        assert r.json() == {"deleted": 0}
        r = await client.post("/api/v1/therapy/sessions/delete", json={"sessions": [{"id": sid}]})
        assert r.json() == {"deleted": 0}

        # The owner still has everything
        r = await client.post("/api/v1/therapy/reflections", json={"sessions": [{"id": sid, "token": token}]})
        assert [x["reflection"] for x in r.json()["reflections"]] == ["my private note"]
        r = await client.post("/api/v1/therapy/insights", json={"sessions": [{"id": sid, "token": token}]})
        assert r.json()["total_sessions"] == 1
    finally:
        await _drop(sid)


async def test_delete_sessions_removes_reflection(client):
    d = await _ask(client)
    sid, token = d["session_id"], d["client_token"]
    r = await client.post("/api/v1/therapy/reflect",
                          json={"session_id": sid, "token": token, "reflection": "A private note"})
    assert r.status_code == 200, r.text
    r = await client.post("/api/v1/therapy/sessions/delete",
                          json={"sessions": [{"id": sid, "token": token}, {"id": "not-a-real-id"}]})
    assert r.status_code == 200 and r.json() == {"deleted": 1}
    assert await _sql("SELECT 1 FROM therapy_sessions WHERE session_id = :s", s=sid) == []
    r = await client.post("/api/v1/therapy/reflections", json={"sessions": [{"id": sid, "token": token}]})
    assert r.json()["reflections"] == []


async def test_legacy_session_without_hash_is_neither_readable_nor_deletable(client):
    """A row without a stored token hash cannot be proved to belong to the
    caller: it is not deleted by id (with or without a token) and expires
    through the retention purge instead (audit: legacy NULL-hash IDOR)."""
    legacy = str(uuid.uuid4())
    await _sql(
        "INSERT INTO therapy_sessions (session_id, emotion, language, reflection_logged, created_at) "
        "VALUES (:s, 'sadness', 'en', 'legacy note', :t)",
        s=legacy, t=datetime.utcnow(),
    )
    try:
        r = await client.post("/api/v1/therapy/reflections",
                              json={"sessions": [{"id": legacy, "token": "anything-at-all"}]})
        assert r.json()["reflections"] == []
        r = await client.post("/api/v1/therapy/sessions/delete", json={"sessions": [{"id": legacy}]})
        assert r.status_code == 200 and r.json() == {"deleted": 0}
        r = await client.post("/api/v1/therapy/sessions/delete",
                              json={"sessions": [{"id": legacy, "token": "anything-at-all"}]})
        assert r.json() == {"deleted": 0}
        assert await _sql("SELECT 1 FROM therapy_sessions WHERE session_id = :s", s=legacy) != []
    finally:
        await _drop(legacy)


async def test_delete_without_token_never_deletes_a_tokened_session(client):
    d = await _ask(client)
    sid, token = d["session_id"], d["client_token"]
    try:
        r = await client.post("/api/v1/therapy/sessions/delete", json={"sessions": [{"id": sid}]})
        assert r.json() == {"deleted": 0}
        assert await _sql("SELECT 1 FROM therapy_sessions WHERE session_id = :s", s=sid) != []
        # A batch mixing a token-less key with a valid one is accepted; only
        # the proven session is deleted.
        r = await client.post("/api/v1/therapy/sessions/delete",
                              json={"sessions": [{"id": str(uuid.uuid4())}, {"id": sid, "token": token}]})
        assert r.json() == {"deleted": 1}
    finally:
        await _drop(sid)



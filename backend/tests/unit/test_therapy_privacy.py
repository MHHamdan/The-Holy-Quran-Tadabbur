"""
Privacy and ownership of spiritual-guidance sessions.

- The user's own message is never stored server-side.
- Session ids are generated by the server; each session has a secret client
  token (only its SHA-256 is stored) that /reflect, /reflections, /insights,
  follow-up /chat turns and /sessions/delete require. Knowing an id is not
  enough to read, overwrite or delete someone's reflection (audit: therapy
  session IDOR).
- A /chat follow-up turn updates its row instead of inserting a duplicate
  (audit: 500 UniqueViolation leaking SQL).
- Sessions older than the retention window are purged, also without new
  writes (startup/daily task).
"""

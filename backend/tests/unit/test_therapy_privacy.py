async def test_expired_sessions_purged_on_next_write(client):
    old = "00000000-0000-4000-8000-00000000a1d0"
    await _sql(
        "INSERT INTO therapy_sessions (session_id, emotion, language, created_at) "
        "VALUES (:s, 'general', 'en', :t)",
        s=old, t=datetime.utcnow() - timedelta(days=THERAPY_RETENTION_DAYS + 1),
    )
    sid = (await _ask(client))["session_id"]
    assert await _sql("SELECT 1 FROM therapy_sessions WHERE session_id = :s", s=old) == []
    await _drop(sid)


async def test_retention_purge_runs_without_new_writes():
    """purge_expired_private_data (run at startup and daily by the router
    lifespan) removes expired rows even when no session is created."""
    from app.db.database import AsyncSessionLocal

    old = "00000000-0000-4000-8000-00000000a1d1"
    fresh = str(uuid.uuid4())
    await _sql(
        "INSERT INTO therapy_sessions (session_id, emotion, language, created_at) "
        "VALUES (:o, 'general', 'en', :t), (:f, 'general', 'en', :n)",
        o=old, t=datetime.utcnow() - timedelta(days=THERAPY_RETENTION_DAYS + 1),
        f=fresh, n=datetime.utcnow(),
    )
    try:
        async with AsyncSessionLocal() as db:
            await therapy_routes.purge_expired_private_data(db)
        assert await _sql("SELECT 1 FROM therapy_sessions WHERE session_id = :s", s=old) == []
        assert await _sql("SELECT 1 FROM therapy_sessions WHERE session_id = :s", s=fresh) != []
    finally:
        await _drop(old, fresh)


async def test_retention_task_is_registered_in_app_lifespan(monkeypatch):
    calls = []

    async def fake_loop():
        calls.append("started")

    monkeypatch.setattr(therapy_routes, "_retention_loop", fake_loop)
    monkeypatch.setattr(therapy_routes, "PRIVACY_PURGE_ENABLED", True)
    async with therapy_routes._retention_lifespan(app):
        import asyncio
        await asyncio.sleep(0)
    assert calls == ["started"]
    assert therapy_routes.router.lifespan_context is therapy_routes._retention_lifespan


async def test_retention_purge_sweeps_expired_search_history():
    """Expired searches leave process memory on the daily purge, not only on
    the session's next search (audit: expired search history kept in RAM)."""
    from app.services import search_history as sh

    svc = sh.search_history_service
    idle, mixed = f"sess_{uuid.uuid4()}", f"sess_{uuid.uuid4()}"
    old = datetime.utcnow() - timedelta(days=sh.SEARCH_HISTORY_TTL_DAYS + 1)
    try:
        await svc.record_search(idle, "old query", "text")
        await svc.record_search(mixed, "stale query", "text")
        await svc.record_search(mixed, "fresh query", "text")
        svc._session_history[idle][0].timestamp = old
        svc._session_history[mixed][0].timestamp = old

        assert await therapy_routes.purge_expired_search_history() == 2

        assert idle not in svc._session_history
        assert [e.query for e in svc._session_history[mixed]] == ["fresh query"]
    finally:
        await svc.clear_session_history(idle)
        await svc.clear_session_history(mixed)

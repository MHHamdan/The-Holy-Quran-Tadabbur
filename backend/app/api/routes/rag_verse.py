@router.post("/verse/explain-word")
async def verse_explain_word(
    body: VerseExplainWordRequest,
    session: AsyncSession = Depends(get_async_session),
    _rate: None = Depends(rag_rate_limit),
):
    """Explain a word from a verse using retrieved tafsir context."""
    _validate_surah_ayah(body.surah, body.ayah_start, body.ayah_end)

    if body.language == "ar":
        question = f"اشرح معنى الكلمة «{body.word}» في هذه الآية شرحاً مختصراً مع ذكر المعنى اللغوي ودلالتها في السياق."
    else:
        question = f"Explain the word \"{body.word}\" in this verse — its linguistic meaning and contextual significance."

    anchored = _compose_anchored_query(
        surah=body.surah,
        ayah_start=body.ayah_start,
        ayah_end=body.ayah_end,
        question=question,
        language=body.language,
    )

    try:
        result = await _run_pipeline(
            session,
            question=anchored,
            language=body.language,
            preferred_sources=body.preferred_sources,
            max_sources=_VERSE_MAX_SOURCES,
        )
    except asyncio.TimeoutError:
        raise HTTPException(
            status_code=504,
            detail={
                "error_code": "timeout",
                "message_en": "Request timed out, please try again",
                "message_ar": "انتهت مهلة الطلب، حاول مرة أخرى",
            },
        )

    payload = result.to_dict() if hasattr(result, "to_dict") else dict(result)
    payload["word"] = body.word
    payload = _attach_verse_metadata(payload, surah=body.surah, ayah_start=body.ayah_start, ayah_end=body.ayah_end)
    payload = _attach_suggestions(payload, body.language)
    return payload


@router.get("/verse/suggested-questions", response_model=SuggestedQuestionsResponse)
def verse_suggested_questions(
    surah: int = Query(..., ge=1, le=114),
    ayah_start: int = Query(..., ge=1),
    ayah_end: Optional[int] = Query(None, ge=1),
    language: str = Query("ar", pattern="^(ar|en)$"),
) -> SuggestedQuestionsResponse:
    """Return bilingual templated suggested questions for the verse.

    The list is intentionally short (3 entries) so the UI can render them
    as one-click chips beside the question input.
    """
    _validate_surah_ayah(surah, ayah_start, ayah_end)
    raw = _SUGGESTED_QUESTION_TEMPLATES.get(language, _SUGGESTED_QUESTION_TEMPLATES["en"])
    return SuggestedQuestionsResponse(
        surah=surah,
        ayah_start=ayah_start,
        ayah_end=ayah_end,
        language=language,
        questions=[SuggestedQuestion(id=q["id"], text=q["text"], language=language) for q in raw],
    )

@router.post("/verse/ask")
async def verse_ask(
    body: VerseAskRequest,
    session: AsyncSession = Depends(get_async_session),
    _rate: None = Depends(rag_rate_limit),
):
    """Answer a free-form question about a specific verse.

    Returns a GroundedResponse (dict). Always includes citations array;
    when no evidence is available the response carries
    `status="no_verified_source"` with the bilingual safe-refusal text
    and a `suggested_questions` list.
    """
    _validate_surah_ayah(body.surah, body.ayah_start, body.ayah_end)

    anchored = _compose_anchored_query(
        surah=body.surah,
        ayah_start=body.ayah_start,
        ayah_end=body.ayah_end,
        question=body.question,
        language=body.language,
    )

    try:
        result = await _run_pipeline(
            session,
            question=anchored,
            language=body.language,
            preferred_sources=body.preferred_sources,
            max_sources=body.max_sources,
        )
    except asyncio.TimeoutError:
        logger.error("verse_ask timeout for %s", _verse_ref_str(body.surah, body.ayah_start, body.ayah_end))
        raise HTTPException(
            status_code=504,
            detail={
                "error_code": "timeout",
                "message_en": "Request timed out, please try again",
                "message_ar": "انتهت مهلة الطلب، حاول مرة أخرى",
            },
        )

    payload = result.to_dict() if hasattr(result, "to_dict") else dict(result)
    payload = _attach_verse_metadata(payload, surah=body.surah, ayah_start=body.ayah_start, ayah_end=body.ayah_end)
    payload = _attach_suggestions(payload, body.language)
    return payload



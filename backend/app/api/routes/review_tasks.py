@router.get("/review/tasks", response_model=ReviewTaskListResponse)
async def list_review_tasks(
    content_type: Optional[str] = Query(None, description="Filter by content type"),
    status: Optional[str] = Query(None, description="Filter by status"),
    priority: Optional[str] = Query(None, description="Filter by priority"),
    source_id: Optional[str] = Query(None, description="Filter by source ID"),
    has_disagreement: Optional[bool] = Query(None, description="Filter tasks with disagreement notes"),
    human_review_required: Optional[bool] = Query(None, description="Filter by humanReviewRequired"),
    story_id: Optional[str] = Query(None, description="Filter by story ID"),
    limit: int = Query(50, ge=1, le=200),
    offset: int = Query(0, ge=0),
):
    """
    List review tasks with optional filters.

    Returns tasks ordered by priority (high first), then contentType, then creation date.
    """
    if content_type and content_type not in VALID_CONTENT_TYPES:
        raise HTTPException(
            status_code=400,
            detail=f"Invalid content_type. Must be one of: {', '.join(sorted(VALID_CONTENT_TYPES))}",
        )
    if status and status not in VALID_STATUSES:
        raise HTTPException(
            status_code=400,
            detail=f"Invalid status. Must be one of: {', '.join(sorted(VALID_STATUSES))}",
        )
    if priority and priority not in VALID_PRIORITIES:
        raise HTTPException(
            status_code=400,
            detail=f"Invalid priority. Must be one of: {', '.join(sorted(VALID_PRIORITIES))}",
        )

    tasks, total = _store.get_all(
        content_type=content_type,
        status=status,
        priority=priority,
        source_id=source_id,
        has_disagreement=has_disagreement,
        human_review_required=human_review_required,
        story_id=story_id,
        limit=limit,
        offset=offset,
    )

    return ReviewTaskListResponse(
        tasks=[_task_to_response(t) for t in tasks],
        total=total,
        offset=offset,
        limit=limit,
    )


@router.get("/review/tasks/{task_id}", response_model=ReviewTaskResponse)
async def get_review_task(
    task_id: str = FPath(..., description="Review task ID"),
):
    """Get a single review task by ID."""
    task = _store.get_by_id(task_id)
    if not task:
        raise HTTPException(status_code=404, detail=f"Review task {task_id!r} not found")
    return _task_to_response(task)


@router.post("/review/tasks/{task_id}/decision", response_model=ReviewTaskResponse)
async def submit_task_decision(
    task_id: str = FPath(..., description="Review task ID"),
    body: SubmitDecisionRequest = ...,
):
    """
    Submit a review decision for a task.

    Safety rules:
    - All decisions require reviewerId and notes (min 10 chars)
    - Decision only updates review metadata — never Quran text or story content
    - Audit trail: every decision is persisted with reviewerId + timestamp
    - Approved tasks gain reviewerId/reviewedAt/notes in the decision field
    - Rejected tasks are flagged and must not be shown as approved in the UI

    Arabic notice:
    لا يعتمد هذا المحتوى إلا بعد مراجعة علمية موثقة.
    (This content is not approved until documented scholarly review is completed.)
    """
    try:
        updated = _store.submit_decision(
            task_id=task_id,
            decision_status=body.status,
            notes=body.notes,
            reviewer_id=body.reviewerId,
            reviewer_name=body.reviewerName,
        )
    except ValueError as e:
        raise HTTPException(status_code=404, detail=str(e))

    return _task_to_response(updated)


@router.get("/review/stats", response_model=ReviewStatsResponse)
async def get_review_stats():
    """
    Get review task dashboard statistics.

    Returns counts by status, content type, priority, and special flags.
    """
    stats = _store.get_stats()
    return ReviewStatsResponse(**stats)



# ---------------------------------------------------------------------------
# QAC word-by-word downloader (qurancdn.com public API)
# ---------------------------------------------------------------------------
QURANCDN_BASE = "https://api.qurancdn.com/api/qdc"


def _fetch_surah_words(surah: int, session: requests.Session) -> list[dict]:
    """Download all words for a surah. Returns list of word dicts."""
    words: list[dict] = []
    page = 1
    while True:
        url = (
            f"{QURANCDN_BASE}/verses/by_chapter/{surah}"
            f"?words=true"
            f"&word_fields=text_uthmani,location,verse_key,char_type_name"
            f"&per_page=500&page={page}"
        )
        for attempt in range(4):
            try:
                r = session.get(url, timeout=30)
                if r.status_code == 200:
                    break
                time.sleep(2 ** attempt)
            except requests.RequestException:
                if attempt == 3:
                    raise
                time.sleep(2 ** attempt)

        data = r.json()
        verses = data.get("verses", [])

        for verse in verses:
            verse_key = verse.get("verse_key", "")
            parts = verse_key.split(":")
            if len(parts) != 2:
                continue
            aya_no = int(parts[1])
            pos_counter = 0
            for w in verse.get("words", []):
                if w.get("char_type_name") != "word":
                    continue
                pos_counter += 1
                loc = w.get("location", "")
                loc_parts = loc.split(":")
                word_pos = int(loc_parts[2]) if len(loc_parts) == 3 else pos_counter

                text_uthmani = w.get("text_uthmani", w.get("text", ""))
                trans = w.get("translation", {})
                meaning_en = trans.get("text") if isinstance(trans, dict) else None

                words.append({
                    "sura_no": surah,
                    "aya_no": aya_no,
                    "word_position": word_pos,
                    "word_ar": text_uthmani,
                    "meaning_en": meaning_en,
                })

        pagination = data.get("pagination", {})
        if page >= pagination.get("total_pages", 1):
            break
        page += 1
        time.sleep(0.15)  # respectful rate limit

    return words


# ---------------------------------------------------------------------------
# Arabic meaning lookup
# ---------------------------------------------------------------------------

def _lookup_meaning_ar(word_ar: str) -> Optional[str]:
    """
    Look up Arabic meaning for a word-form.

    Strategy (in order):
    1. bare form (diacritics stripped + Alef normalised)
    2. strip ال definite article prefix
    3. strip single-char prefix particles (و ف ب ل ك)
    4. strip prefix + ال
    5. strip two-char prefix
    Falls back to None when not found.
    """
    bare = _strip(word_ar)

    if bare in _AR_MEANINGS:
        return _AR_MEANINGS[bare]

    # Strip definite article الـ
    if bare.startswith("ال") and len(bare) > 3:
        stem = bare[2:]
        if stem in _AR_MEANINGS:
            return _AR_MEANINGS[stem]

    # Strip single prefix particle
    if len(bare) > 2:
        stem1 = bare[1:]
        if stem1 in _AR_MEANINGS:
            return _AR_MEANINGS[stem1]
        # strip prefix then ال
        if stem1.startswith("ال") and len(stem1) > 3:
            stem1al = stem1[2:]
            if stem1al in _AR_MEANINGS:
                return _AR_MEANINGS[stem1al]

    # Strip two-char prefix (e.g. فال، وال، بال)
    if len(bare) > 4:
        stem2 = bare[2:]
        if stem2 in _AR_MEANINGS:
            return _AR_MEANINGS[stem2]
        if stem2.startswith("ال") and len(stem2) > 3:
            if stem2[2:] in _AR_MEANINGS:
                return _AR_MEANINGS[stem2[2:]]

    return None



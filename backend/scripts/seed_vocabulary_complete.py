def seed_surah(surah: int, db_session, http: requests.Session, dry_run: bool) -> tuple[int, int]:
    """Seed one surah. Returns (words_fetched, rows_written)."""
    print(f"  Surah {surah:>3} … ", end="", flush=True)
    words = _fetch_surah_words(surah, http)

    rows: list[dict] = []
    ar_hits = 0
    for w in words:
        word_ar = w["word_ar"]
        bare = _strip(word_ar)
        meaning_ar = _lookup_meaning_ar(word_ar)
        if meaning_ar:
            ar_hits += 1
        rows.append({
            "sura_no": w["sura_no"],
            "aya_no": w["aya_no"],
            "word_position": w["word_position"],
            "word_ar": word_ar,
            "word_ar_bare": bare,
            "root_ar": None,
            "pattern_ar": None,
            "pos_tag": None,
            "meaning_en": w["meaning_en"],
            "meaning_ar": meaning_ar,
            "source_id": SOURCE_ID,
        })

    written = 0
    if not dry_run and rows:
        CHUNK = 500
        for i in range(0, len(rows), CHUNK):
            written += _bulk_upsert(db_session, rows[i : i + CHUNK])

    print(f"{len(words):5} words  |  ar_meanings: {ar_hits:4}  |  written: {written if not dry_run else '(dry)'}")
    return len(words), written


def main() -> None:
    parser = argparse.ArgumentParser(description="Seed complete Quranic vocabulary")
    parser.add_argument("--sura", type=int, default=None, help="Seed only one surah (1-114)")
    parser.add_argument("--dry-run", action="store_true", help="Fetch and parse only, skip DB writes")
    args = parser.parse_args()

    surahs = [args.sura] if args.sura else list(range(1, 115))

    print(f"Seeding {len(surahs)} surah(s)  |  source: {SOURCE_ID}  |  dry_run={args.dry_run}")

    http = requests.Session()
    http.headers["User-Agent"] = "Tadabbur-Quran-Seed/1.0"

    db_session = SyncSessionLocal() if not args.dry_run else None

    total_words = 0
    total_written = 0
    try:
        for surah in surahs:
            fetched, written = seed_surah(surah, db_session, http, args.dry_run)
            total_words += fetched
            total_written += written
    finally:
        if db_session:
            db_session.close()

    print()
    print(f"Done — {total_words:,} words fetched  |  {total_written:,} rows written to vocabulary_entries")
    print(f"Arabic meanings cover ~{len(_AR_MEANINGS)} unique word-forms from Mufradat Al-Raghib Al-Isfahani.")


if __name__ == "__main__":
    main()

/**
 * Select today's word using date-seeded deterministic index.
 * djb2-based hash so the same date always yields the same word.
 */
export function getTodayWord(dateStr: string = new Date().toISOString().slice(0, 10)): VocabEntry {
  let h = 5381;
  for (let i = 0; i < dateStr.length; i++) {
    h = ((h << 5) + h + dateStr.charCodeAt(i)) >>> 0;
  }
  return WORD_OF_DAY_VOCAB[h % WORD_OF_DAY_VOCAB.length];
}
